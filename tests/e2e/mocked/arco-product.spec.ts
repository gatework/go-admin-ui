import { test, expect } from '@playwright/test'
import { authenticate, installApiMocks, userInfo } from './fixtures'
import { json } from './support/crud'

test('Arco product validates, creates, edits and cancels/confirms deletion', async({ page, context }) => {
  await authenticate(context)
  const { calls } = await installApiMocks(page)
  await page.route('**/api/v1/getinfo*', route => route.fulfill(json({ ...userInfo, data: { ...userInfo.data, permissions: [...userInfo.data.permissions, 'demo:product:delete'] }})))
  await page.goto('/#/demo/product')
  const table = page.locator('.arco-table')
  await expect(table.getByText('Alpha', { exact: true })).toBeVisible()
  await page.locator('#loader-wrapper').waitFor({ state: 'detached' })
  await page.screenshot({ path: 'output/playwright/arco-product-desktop.png' })
  await page.getByRole('button', { name: '新增', exact: true }).click()
  const modal = page.locator('.arco-modal')
  await expect(modal).toBeVisible()
  await modal.getByRole('button', { name: '保存' }).click()
  await expect(modal.getByText('请填写名称')).toBeVisible()
  expect(calls.product.create).toBe(0)
  await modal.getByPlaceholder('请输入名称').fill('Gamma')
  await modal.getByPlaceholder('请输入编码').fill('G-003')
  await modal.getByRole('button', { name: '保存' }).click()
  await expect.poll(() => calls.product.create).toBe(1)
  await expect(modal).toBeHidden()
  await expect(page.getByRole('button', { name: '新增', exact: true })).toBeFocused()
  const alpha = table.getByRole('row').filter({ hasText: 'Alpha' })
  await alpha.getByRole('button', { name: '修改', exact: true }).click()
  await expect(modal.getByPlaceholder('请输入名称')).toHaveValue('Alpha')
  await modal.getByPlaceholder('请输入名称').fill('Updated')
  await modal.getByRole('button', { name: '保存' }).click()
  await expect.poll(() => calls.product.update).toBe(1)
  await expect(modal).toBeHidden()
  await alpha.locator('.arco-checkbox').click()
  await expect(alpha.getByRole('checkbox')).toBeChecked()
  const remove = page.locator('.pro-table__toolbar').getByRole('button', { name: '删除', exact: true })
  await expect(remove).toBeEnabled()
  await remove.click()
  await page.locator('.arco-modal').getByRole('button', { name: '取消', exact: true }).click()
  expect(calls.product.remove).toBe(0)
  await remove.click()
  await page.locator('.arco-modal').getByRole('button', { name: '删除', exact: true }).click()
  await expect.poll(() => calls.product.remove).toBe(1)
  await expect(remove).toBeDisabled()
})

test('Arco product renders native cells on mobile and searches from its sheet', async({ page, context }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await authenticate(context)
  const { calls } = await installApiMocks(page)
  await page.goto('/#/demo/product')
  await expect(page.locator('.pro-card')).toHaveCount(2)
  await expect(page.locator('.arco-table')).toHaveCount(0)
  const first = page.locator('.pro-card').first()
  await expect(first.getByText('Alpha', { exact: true })).toBeVisible()
  await expect(first.locator('.arco-tag')).toHaveText('正常')
  await page.locator('#loader-wrapper').waitFor({ state: 'detached' })
  await page.screenshot({ path: 'output/playwright/arco-product-mobile.png' })
  await first.getByRole('button', { name: '操作', exact: true }).click()
  await first.getByRole('button', { name: '修改', exact: true }).click()
  const modal = page.locator('.arco-modal')
  await expect(modal.getByPlaceholder('请输入名称')).toHaveValue('Alpha')
  await modal.getByRole('button', { name: '取 消' }).click()
  await page.locator('.pro-table__filter-bar').getByRole('button').click()
  await page.locator('.pro-table__sheet').getByPlaceholder('请输入名称').fill('Beta')
  await page.locator('.pro-table__sheet').getByRole('button', { name: '查看结果' }).click()
  await expect.poll(() => calls.product.listQueries.at(-1)).toContain('name=Beta')
  await expect(page.locator('.pro-table__sheet')).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
