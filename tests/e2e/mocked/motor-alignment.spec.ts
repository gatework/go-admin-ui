test('selected palette reaches custom controls and pinned preferences release keyboard focus', async({ page, context }) => {
  await authenticate(context); await installApiMocks(page)
  await page.goto('/#/demo/product')
  const drawer = await openPreferences(page)
  await drawer.getByRole('button', { name: '紫罗兰', exact: true }).click()
  await drawer.getByRole('tab', { name: '拓展', exact: true }).click()
  await drawer.getByRole('switch', { name: '启用水印', exact: true }).click()
  await expect.poll(() => drawer.getByRole('switch', { name: '启用水印', exact: true }).evaluate(el => {
    const probe = document.createElement('span'); probe.style.color = 'rgb(var(--primary-6))'; el.append(probe)
    const result = { control: getComputedStyle(el).backgroundColor, primary: getComputedStyle(probe).color }; probe.remove(); return result.control === result.primary
  })).toBe(true)
  await drawer.getByRole('button', { name: '固定偏好面板' }).click()
  await expect(drawer).not.toHaveAttribute('aria-modal', 'true')
  await page.locator('#hamburger-container').focus()
  await page.keyboard.press('Tab')
  expect(await drawer.evaluate(el => el.contains(document.activeElement))).toBe(false)
  await drawer.getByRole('button', { name: '关闭偏好设置' }).click()
  await expect(page.locator('.app-watermark')).toBeVisible()
})

