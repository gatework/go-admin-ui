test('forgotten lock password can cancel and sign out above the lock, preserving appearance', async({ page, context }) => {
  await authenticate(context); await installApiMocks(page); await installLoginMocks(page)
  await page.goto('/#/dashboard')
  const drawer = await openPreferences(page)
  await drawer.getByRole('button', { name: '紫罗兰', exact: true }).click()
  await drawer.getByRole('tab', { name: '拓展', exact: true }).click()
  await drawer.getByRole('button', { name: '设置锁屏密码', exact: true }).click()
  const passwordDialog = page.locator('.password-dialog')
  await passwordDialog.locator('input').nth(0).fill('local123')
  await passwordDialog.locator('input').nth(1).fill('local123')
  await passwordDialog.getByRole('button').last().click()
  const lock = page.locator('.lock-screen')
  const forgot = lock.getByRole('button', { name: '忘记锁屏密码？退出当前账号', exact: true })
  await forgot.click()
  const confirmation = page.getByRole('dialog', { name: '退出当前账号？', exact: true })
  await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  await expect(lock).toBeVisible()
  await forgot.focus(); await page.keyboard.press('Enter')
  const signout = confirmation.getByRole('button', { name: '退出登录', exact: true })
  await signout.click({ trial: true })
  await signout.focus(); await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#\/login/)
  await expect(lock).toBeHidden()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('motor-admin-ui-preferences')!).themePreset)).toBe('violet')
})

test('login boots when browser storage is blocked', async({ page }) => {
  await page.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('blocked', 'SecurityError') } }))
  await installLoginMocks(page)
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/login')
  await expect(page.locator('.captcha-img')).toBeVisible()
  expect(errors).toEqual([])
})
