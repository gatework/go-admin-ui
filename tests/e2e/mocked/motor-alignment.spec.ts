import { test, expect } from '@playwright/test'
import { authenticate, installApiMocks, installLoginMocks } from './fixtures'

const openPreferences = async(page: import('@playwright/test').Page) => {
  await page.locator('#layout-settings').click()
  return page.getByRole('dialog', { name: '偏好设置', exact: true })
}

test('preferences apply theme, layout, persistence and reset', async({ page, context }) => {
  await authenticate(context); await installApiMocks(page)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/#/dashboard')
  const drawer = await openPreferences(page)
  await drawer.getByRole('button', { name: '暗色', exact: true }).click()
  await expect(page.locator('body')).toHaveAttribute('arco-theme', 'dark')
  await expect(page.locator('#loader-wrapper')).toBeHidden()
  await page.locator('.arco-drawer').evaluateAll(elements => Promise.allSettled(elements.flatMap(el => el.getAnimations({ subtree: true }).map(animation => animation.finished))))
  await page.screenshot({ animations: 'disabled', path: '/tmp/motor-preferences-dark.png' })
  await drawer.getByRole('tab', { name: '布局', exact: true }).click()
  await drawer.getByRole('button', { name: '内容全屏', exact: true }).click()
  await expect(page.locator('.sidebar-container')).toBeHidden()
  await drawer.getByRole('button', { name: '关闭偏好设置' }).click()
  await expect(page.locator('.preferences-recovery')).toBeVisible()
  await page.reload()
  await expect(page.locator('.preferences-recovery')).toBeVisible()
  await expect(page.locator('body')).toHaveAttribute('arco-theme', 'dark')
  await page.locator('.preferences-recovery').click()
  await drawer.getByRole('button', { name: '恢复默认', exact: true }).click()
  await page.getByRole('button', { name: '确认恢复', exact: true }).click()
  await expect(page.locator('.sidebar-container')).toBeVisible()
  await expect(page.locator('body')).not.toHaveAttribute('arco-theme', 'dark')
})

