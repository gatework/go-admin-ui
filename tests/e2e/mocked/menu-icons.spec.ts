import { test, expect } from '@playwright/test'
import { authenticate, installApiMocks } from './fixtures'
test('menu editor selects an Arco icon and preserves it in the update', async({ page, context }) => {
  await authenticate(context); await installApiMocks(page)
  await page.goto('/#/admin/sys-menu')
  await page.getByRole('row', { name: /用户管理/ }).getByRole('button', { name: '修改', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '修改菜单' })
  const picker = dialog.locator('.arco-icon-select')
  await picker.click()
  await picker.locator('input').fill('settings')
  await page.getByRole('option', { name: 'settings', exact: true }).click()
  await expect(picker).toContainText('settings')
  const saved = page.waitForRequest(request => request.url().includes('/api/v1/menu') && request.method() === 'PUT')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  expect((await saved).postDataJSON()).toMatchObject({ icon: 'settings' })
})

test('Arco icons keep one size across menu groups, pages and menu table', async({ page, context }) => {
  await authenticate(context); await installApiMocks(page)
  await page.goto('/#/admin/sys-menu')
  await expect(page.locator('.arco-table')).toBeVisible()
  const sizes = await page.locator('.sidebar-container .menu-icon:visible, .arco-table .menu-icon:visible').evaluateAll(elements => elements.map(el => ({ width: el.getBoundingClientRect().width, height: el.getBoundingClientRect().height, use: !!el.querySelector('use') })))
  expect(sizes.length).toBeGreaterThan(5)
  expect(sizes.every(size => size.width === 18 && size.height === 18 && !size.use)).toBe(true)
  await page.getByRole('row', { name: /用户管理/ }).getByRole('button', { name: '修改', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '修改菜单' })
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeInViewport()
  await expect(page.locator('#loader-wrapper')).toBeHidden()
  await page.screenshot({ animations: 'disabled', path: '/tmp/motor-menu-editor-desktop.png' })
  await page.setViewportSize({ width: 375, height: 812 })
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeInViewport()
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ animations: 'disabled', path: '/tmp/motor-menu-editor-mobile.png' })
})
