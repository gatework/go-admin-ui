test('email recovery and password confirmation preserve one-use credentials', async({ page }, info) => {
  await publicMocks(page)
  await page.route('**/api/v1/account/password/forgot', route => route.fulfill({ json: { code: 200 }}))
  let reset: Record<string, string> = {}
  await page.route('**/api/v1/account/password/reset', route => { reset = route.request().postDataJSON(); return route.fulfill({ json: { code: 200 }}) })
  await page.goto('/#/forgot-password'); await page.getByLabel('邮箱', { exact: true }).fill('member@example.test')
  await page.getByRole('button', { name: '找回密码', exact: true }).click()
  await expect(page.getByText('如果该邮箱关联有效账户，重置邮件将很快送达。')).toBeVisible()
  await page.goto('/#/reset-password?token=one-use-token&email=member@example.test')
  await page.getByLabel('邮箱验证码', { exact: true }).fill('123456')
  await page.getByLabel('密码', { exact: true }).fill('Changed-password-123')
  await page.getByLabel('确认密码', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: '重置密码', exact: true }).click()
  await expect(page.getByText('两次输入的密码不一致')).toBeVisible()
  expect(reset).toEqual({})
  await page.getByLabel('确认密码', { exact: true }).fill('Changed-password-123')
  await page.getByLabel('确认密码', { exact: true }).blur()
  await expect(page.getByText('两次输入的密码不一致')).toHaveCount(0)
  await expect(page.locator('#nprogress')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('password-reset.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '重置密码', exact: true }).click()
  await expect(page.getByText('密码已更新，旧登录已失效，请重新登录。')).toBeVisible()
  expect(reset.token).toBe('one-use-token')
  await expect(page.getByRole('link', { name: '找回密码', exact: true })).toHaveCount(0)
  await expect(page.locator('#nprogress')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('password-reset-success.png'), animations: 'disabled' })
})
