import { test, expect } from '@playwright/test'
import { authenticate, installApiMocks } from './fixtures'

test('the local Arco designer follows host appearance without losing edits', async({ page, context }) => {
  await authenticate(context)
  await installApiMocks(page)
  const errors: string[] = []
  const legacyRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (request.url().includes(':8000/form-generator/')) legacyRequests.push(request.url())
  })
  await page.goto('/#/dev-tools/build')
  await page.locator('#loader-wrapper').waitFor({ state: 'detached' })
  const host = page.locator('iframe[title="表单构建"]')
  await expect(host).toHaveAttribute('src', /^\/form-generator\/index.html\?/)
  const frame = page.frameLocator('iframe')
  await frame.getByRole('button', { name: '单行文本', exact: true }).click()
  await frame.getByRole('textbox', { name: '标题', exact: true }).fill('Account draft')
  const originalSource = await host.getAttribute('src')
  await page.getByRole('button', { name: '语言', exact: true }).click()
  await page.getByRole('menuitem', { name: 'English', exact: true }).click()
  await expect(frame.getByRole('button', { name: 'Preview', exact: true })).toBeVisible()
  await expect(page.locator('iframe')).toHaveAttribute('src', originalSource!)
  await page.evaluate(() => document.body.setAttribute('arco-theme', 'dark'))
  await expect(frame.locator('body')).toHaveAttribute('arco-theme', 'dark')
  await expect(frame.getByRole('textbox', { name: 'Label', exact: true })).toHaveValue('Account draft')
  await expect(frame.locator('.builder-field')).toHaveCount(1)
  expect(legacyRequests).toEqual([])
  expect(errors).toEqual([])
})

test('the builder fits the shell through resize, layout changes and cached navigation', async({ page, context }) => {
  await authenticate(context)
  await installApiMocks(page)
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/#/dev-tools/build')
  await page.locator('#loader-wrapper').waitFor({ state: 'detached' })
  const frame = page.frameLocator('iframe')
  await frame.getByRole('button', { name: '单行文本', exact: true }).click()
  await frame.getByRole('textbox', { name: '标题', exact: true }).fill('Retained layout draft')
  const source = await page.locator('iframe').getAttribute('src')
  const fits = () => page.evaluate(() => {
    const box = document.querySelector('.form-builder-frame')?.getBoundingClientRect()
    if (!box) return false
    const footer = document.querySelector('.main-container > .app-footer')?.getBoundingClientRect()
    return box.height > 0 && box.bottom <= (footer?.top ?? innerHeight) - 10 && document.documentElement.scrollHeight <= innerHeight + 1 && document.documentElement.scrollWidth <= innerWidth
  })
  for (const viewport of [{ width: 1600, height: 1000 }, { width: 1440, height: 900 }, { width: 1280, height: 720 }, { width: 390, height: 700 }]) {
    await page.setViewportSize(viewport)
    await expect.poll(fits).toBe(true)
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.locator('#layout-settings').click()
  const drawer = page.getByRole('dialog', { name: '偏好设置', exact: true })
  await drawer.getByRole('tab', { name: '布局', exact: true }).click()
  await drawer.getByRole('button', { name: '内容全屏', exact: true }).click()
  await drawer.getByRole('button', { name: '关闭偏好设置' }).click()
  await expect.poll(fits).toBe(true)
  await expect(page.locator('iframe')).toHaveAttribute('src', source!)
  await expect(frame.getByRole('textbox', { name: '标题', exact: true })).toHaveValue('Retained layout draft')

  await page.locator('.preferences-recovery').click()
  await drawer.getByRole('button', { name: '垂直', exact: true }).click()
  await drawer.getByRole('switch', { name: '显示底栏', exact: true }).click()
  await drawer.getByRole('switch', { name: '显示顶栏', exact: true }).click()
  await drawer.getByRole('button', { name: '关闭偏好设置' }).click()
  await expect.poll(fits).toBe(true)
  await expect(page.locator('iframe')).toHaveAttribute('src', source!)
  await expect(frame.getByRole('textbox', { name: '标题', exact: true })).toHaveValue('Retained layout draft')

  await page.goto('/#/demo/product')
  await expect(page.locator('.arco-table').first()).toBeVisible()
  await page.setViewportSize({ width: 1280, height: 640 })
  await page.goto('/#/dev-tools/build')
  await expect.poll(fits).toBe(true)
  await expect(frame.locator('.field-select').first()).toContainText('Retained layout draft')
})

test('theme controls update the canvas, rich text and code editor while retaining edits', async({ page, context }) => {
  await authenticate(context)
  await installApiMocks(page)
  await page.setViewportSize({ width: 1440, height: 1000 })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/dev-tools/build')
  await page.locator('#loader-wrapper').waitFor({ state: 'detached' })
  const frame = page.frameLocator('iframe')
  await frame.locator('.palette').getByRole('button', { name: '富文本', exact: true }).click()
  await frame.getByRole('textbox', { name: '标题', exact: true }).fill('Theme retained draft')
  const content = frame.frameLocator('.rich-text iframe').locator('body')
  await expect(content).toBeEditable()
  const lightEditorBackground = await content.evaluate(el => getComputedStyle(el).backgroundColor)
  await content.fill('Content survives theme changes')
  const source = await page.locator('iframe').getAttribute('src')
  const lightCanvas = await frame.locator('.canvas').evaluate(el => getComputedStyle(el.parentElement!).backgroundColor)
  await page.getByRole('button', { name: '切换为暗色模式', exact: true }).click()
  await expect(frame.locator('body')).toHaveAttribute('arco-theme', 'dark')
  await expect(content).toHaveText('Content survives theme changes')
  await expect(content).toHaveCSS('background-color', 'rgb(34, 47, 62)')
  expect(await frame.locator('.canvas').evaluate(el => getComputedStyle(el.parentElement!).backgroundColor)).not.toBe(lightCanvas)
  await page.screenshot({ path: 'test-results/form-builder-dark.png', fullPage: true })
  await frame.getByRole('button', { name: '查看代码', exact: true }).click()
  const editor = frame.getByRole('textbox', { name: '查看代码', exact: true })
  await editor.fill('<template><p>Keep this code edit</p></template>')
  const darkEditor = await frame.locator('.cm-editor').evaluate(el => getComputedStyle(el).color)
  await page.getByRole('button', { name: '切换为亮色模式', exact: true }).click()
  await expect(frame.locator('body')).not.toHaveAttribute('arco-theme', 'dark')
  await expect(editor).toContainText('Keep this code edit')
  await expect.poll(() => frame.locator('.cm-editor').evaluate(el => getComputedStyle(el).color)).not.toBe(darkEditor)
  await frame.locator('.arco-modal-close-btn').click()
  await expect(content).toHaveText('Content survives theme changes')
  await expect(content).toHaveCSS('background-color', lightEditorBackground)
  await expect(page.locator('iframe')).toHaveAttribute('src', source!)
  await expect(frame.getByRole('textbox', { name: '标题', exact: true })).toHaveValue('Theme retained draft')
  await page.screenshot({ path: 'test-results/form-builder-light.png', fullPage: true })
  expect(errors).toEqual([])
})
