import { expect, test } from '@playwright/test'
import { installApiMocks, userInfo } from './mocked/fixtures'

test('tests login, captures and analyzes native Hillstone evidence through real Go HTTP and SQLite', async({ page, context, request }) => {
  test.skip(process.env.FIREWALL_INTEGRATION !== '1', 'Use playwright.firewall-integration.config.ts to start the disposable backend.')
  const fixtureResponse = await request.get('http://127.0.0.1:18039/__fixture')
  expect(fixtureResponse.ok()).toBe(true)
  const fixture = await fixtureResponse.json() as { token: string, instanceId: number, configuration: string }
  await context.addCookies([{ name: 'Admin-Token', value: fixture.token, domain: 'localhost', path: '/', httpOnly: false, secure: false, sameSite: 'Lax' }])
  await installApiMocks(page)
  await page.route('**/api/v1/network-device-group*', route => route.fulfill({ json: { code: 200, data: { items: [], totalDeviceCount: 1, ungroupedDeviceCount: 1 }}}))
  await page.route('**/api/v1/getinfo*', route => route.fulfill({ json: { ...userInfo, data: { ...userInfo.data, permissions: ['list', 'query', 'import', 'edit', 'design', 'collect', 'connection'].map(value => `network:firewall:${value}`) }}}))
  await page.route('**/api/v1/menurole*', route => route.fulfill({ json: { code: 200, data: [{ path: '/network', component: 'Layout', visible: '0', menuName: 'NetworkManagement', menuType: 'M', title: '网络管理', children: [{ path: 'firewall', component: '/network/firewall/index', visible: '0', menuName: 'NetworkFirewallObjects', menuType: 'C', title: '防火墙对象' }, { path: 'firewall/query', component: '/network/firewall/query', visible: '0', menuName: 'NetworkFirewallQuery', menuType: 'C', title: '策略查询' }, { path: 'firewall/design', component: '/network/firewall/design', visible: '0', menuName: 'NetworkFirewallDesign', menuType: 'C', title: '策略设计' }] }] }}))
  // This bypasses the shell's catch-all. No firewall endpoint is fulfilled or
  // rewritten: the browser talks directly to the real loopback Go HTTP server.
  await page.route('**/api/v1/network-firewall/**', route => route.continue())
  const realResponses: string[] = []
  page.on('response', response => { if (response.url().includes('/api/v1/network-firewall/') && response.headers()['x-firewall-fixture'] === 'real-go-sqlite') realResponses.push(response.url()) })
  await page.goto('/#/network/firewall')
  await expect(page.locator('.fw-device-workspace')).toContainText('Hillstone fixture')
  await page.locator('.fw-device-workspace thead .arco-checkbox').first().click()
  await page.getByRole('button', { name: '测试登录', exact: true }).click()
  await expect(page.locator('.fw-batch-detail')).toContainText('登录成功，会话已关闭', { timeout: 20000 })
  await page.reload()
  await expect(page.locator('.fw-batch-detail')).toContainText('登录成功，会话已关闭')
  await page.getByRole('tab', { name: '设备接入', exact: true }).click()
  await page.locator('.fw-device-workspace thead .arco-checkbox').first().click()
  await page.getByRole('button', { name: '采集配置', exact: true }).click()
  await expect(page.locator('.fw-batch-detail')).toContainText('完整采集', { timeout: 20000 })
  if (process.env.FIREWALL_CAPTURE) await page.screenshot({ path: '../output/playwright/firewall-collection.png', fullPage: true, animations: 'disabled' })
  await page.locator('.fw-batch-detail').getByRole('button', { name: '配置对象', exact: true }).click()
  await expect(page.locator('.fw-main').getByRole('button', { name: '查看详情', exact: true }).first()).toBeVisible(); await expect(page.getByText('hillstone-go-2', { exact: true })).toBeVisible()
  await page.locator('.fw-main').getByRole('button', { name: '查看详情', exact: true }).first().click()
  await expect(page.getByRole('dialog', { name: '查看详情', exact: true })).toContainText('原生对象字段')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '保护范围', exact: true }).click()
  const protection = page.getByRole('dialog', { name: '保护范围', exact: true })
  await protection.getByRole('button', { name: '从当前配置填入安全区域', exact: true }).click()
  await expect(protection.getByRole('textbox', { name: '安全域 1', exact: true })).toHaveValue('inside')
  await expect(protection.getByRole('textbox', { name: '安全域 2', exact: true })).toHaveValue('outside')
  await protection.locator('.fw-binding').first().locator('.arco-checkbox').click()
  await expect(protection.locator('.fw-binding').nth(1).getByRole('checkbox')).not.toBeChecked()
  const settings = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().endsWith('/settings'))
  await protection.getByRole('button', { name: '保存保护范围', exact: true }).click()
  const savedSettings = await (await settings).json()
  expect(savedSettings.code).toBe(200); expect(savedSettings.data.version).toBe(2)
  await expect(protection).toContainText('192.0.2.0/24')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '策略查询', exact: true }).click()
  await page.getByRole('textbox', { name: '标题', exact: true }).fill('Real SQLite traffic')
  await page.getByRole('tab', { name: '粘贴 CSV / TSV / Excel 数据', exact: true }).click()
  await page.getByRole('textbox', { name: '粘贴 CSV / TSV / Excel 数据', exact: true }).fill('source\tdestination\tservice\n192.0.2.10\t198.51.100.10\t443')
  await page.getByRole('button', { name: '解析输入', exact: true }).click()
  await expect(page.getByText('已补充默认 TCP 协议', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '保存查询', exact: true }).click()
  await expect(page).toHaveURL(/request=\d+/)
  await page.getByRole('button', { name: '开始分析', exact: true }).click()
  await expect(page).toHaveURL(/analysis=\d+/)
  const createDraft = page.getByRole('button', { name: '从此分析创建设计草稿', exact: true })
  await expect(createDraft).toBeEnabled({ timeout: 20000 })
  await expect(page.getByRole('tab', { name: /允许 \([1-9]/ })).toBeVisible()
  await createDraft.click()
  await expect(page).toHaveURL(/firewall\/design\?draft=\d+/)
  await expect(page.locator('.fw-main')).toContainText('验证证据', { timeout: 20000 })
  expect(realResponses.length).toBeGreaterThan(12)
  const evidenceResponse = await request.get('http://127.0.0.1:18039/__fixture/evidence')
  const evidence = await evidenceResponse.json()
  expect(evidence.counts).toEqual({ imports: 0, snapshots: 1, requests: 1, rows: 1, analyses: 1, drafts: 1 })
  expect(evidence.collection).toEqual({ opens: 2, reads: 1, closes: 2 })
  expect(evidence.currentRevision).toMatch(/^[a-f0-9]{64}$/)
  expect(evidence.settingsVersion).toBe(2)
  if (process.env.FIREWALL_CAPTURE) await page.screenshot({ path: '../output/firewall-ui/real-http-sqlite-draft.png', fullPage: true, animations: 'disabled' })
})
